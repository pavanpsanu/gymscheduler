// Group meals by their meal type for display
export const getMealsByType = (plan) => {
  const grouped = {};
  plan.forEach((item) => {
    if (!grouped[item.meal]) grouped[item.meal] = [];
    grouped[item.meal].push(item);
  });
  return grouped;
};

